// Generate CoreUI 5.0.0, pinned to the user's HTML reference.
// Prefix every class to avoid collisions with Tailwind (notably .collapse,
// .table and Bootstrap's !important spacing utilities). No reboot or utilities.
import fs from 'node:fs'
import postcss from 'postcss'

const source = 'node_modules/@coreui/coreui/dist/css/coreui.css'
const ast = postcss.parse(fs.readFileSync(source, 'utf8'))
const components = /\.(?:sidebar|header|footer|breadcrumb|btn|card|badge|avatar|progress|form-control|form-select|form-label|table)(?:[\s.:>#\[,-]|$)/
ast.walkComments((node) => { if (!node.text.startsWith('!')) node.remove() })
ast.walkRules((rule) => {
  if (rule.selector.includes(':root') || /^\[data-coreui-theme=["']?dark/.test(rule.selector) && rule.nodes.some((n) => n.prop === '--cui-body-color')) return
  if (!components.test(rule.selector)) { rule.remove(); return }
  rule.selector = rule.selector.replace(/\.([a-zA-Z_][\w-]*)/g, '.qms-cui-$1')
})
ast.walkAtRules((rule) => {
  if (rule.name === 'charset' || !rule.nodes?.length || rule.name.endsWith('keyframes')) rule.remove()
})
fs.writeFileSync('app/coreui.generated.css', '/* Generated by scripts/generate-coreui-theme.mjs. Do not edit. */\n' + ast.toString())
console.log('Generated isolated CoreUI visual components.')
